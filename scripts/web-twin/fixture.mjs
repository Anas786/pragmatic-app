// Builds fixtures/lucky.json — the smoke test's input — from the app's own
// Lucky Cement Nooriabad mock (src/data/mock/sld.ts): the raw `sldV2` graph
// (`sldGraphMock`, verbatim backend schema) and its readings
// (`sldMockValues`, "live.pN.value" → number) wrapped in the
// `/protected/data/all` → `live.data` envelope the app sends the page:
//   { live: { pN: { value, update_at } }, update_at }
// `update_at` is 0 here; smoke.mjs re-stamps it to "a minute ago".
//
// Usage: node scripts/web-twin/fixture.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { ROOT, HERE } from './lib.mjs';

const require = createRequire(import.meta.url);
const ts = require(path.join(ROOT, 'node_modules/typescript'));

const SRC = path.join(ROOT, 'src/data/mock/sld.ts');
const OUT = path.join(HERE, 'fixtures/lucky.json');

const js = ts.transpileModule(fs.readFileSync(SRC, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
  fileName: SRC,
}).outputText;
const mod = { exports: {} };
// the mock only imports types (`src/types`), erased by the transpile
vm.runInNewContext(js, {
  module: mod,
  exports: mod.exports,
  require: (id) => {
    throw new Error(`fixture.mjs: unexpected runtime import "${id}" in ${SRC}`);
  },
});
const { sldGraphMock: sld, sldMockValues: values } = mod.exports;
if (!sld || !Array.isArray(sld.nodes) || !values) throw new Error('fixture.mjs: sldGraphMock / sldMockValues not found');

const live = { live: {}, update_at: 0 };
for (const [key, value] of Object.entries(values)) {
  const [store, param, field] = key.split('.');
  if (store !== 'live' || !param || !field) throw new Error(`fixture.mjs: unexpected value key ${key}`);
  live.live[param] ??= { update_at: 0 };
  live.live[param][field] = value;
}

const fixture = {
  source: 'src/data/mock/sld.ts (sldGraphMock + sldMockValues), generated by scripts/web-twin/fixture.mjs',
  siteName: 'Lucky Cement Nooriabad',
  sld,
  live,
};
fs.writeFileSync(OUT, JSON.stringify(fixture, null, 1) + '\n');
console.log(`${path.relative(ROOT, OUT)}: ${sld.nodes.length} nodes, ${sld.edges.length} edges, ${Object.keys(live.live).length} params`);
